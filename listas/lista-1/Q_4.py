nta1 = float(input("Digite a primeira nota: "))
nta2 = float(input("Digite a segunda nota: "))
nta3 = float(input("Digite a terceira nota: "))
nta4 = float(input("Digite a quarta nota: "))

md = (nta1 + nta2 + nta3 + nta4) / 4

print(f'\nA média entre as notas {nta1}, {nta2}, {nta3} e {nta4} é igual a: {md}')