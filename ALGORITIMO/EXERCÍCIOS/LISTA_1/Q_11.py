n1 = int(input("Digite um número inteiro: "))
n2 = int(input("Digite outro número inteiro: "))
n3 = float(input("Digite um número real: "))

prdt = (n1 * 2) * (n2 / 2)
sma = (n1 * 3) + n3
cbo = n3 ** 3

print(f"O produto do dobro do primeiro com metade do segundo é: {prdt}")
print(f"A soma do triplo do primeiro com o terceiro é: {sma}")
print(f"O terceiro elevado ao cubo é: {cbo}")